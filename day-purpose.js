function weeklyFocus(day, settings) {
  if (day.index === 48) return 'Финальный день: сравни фото, замеры и самочувствие. Отметь, какие движения стали увереннее; максимальные попытки не нужны.';

  if (day.type === 'strength') {
    if (settings.easy === true) return settings.shortSessions === false
      ? 'Сегодня — два облегчённых подхода и нижняя граница повторений. Заканчивай с запасом сил.'
      : 'Сегодня — один облегчённый круг и нижняя граница повторений. Заканчивай с запасом сил.';
    return getWeekInfo(day.week, settings).note;
  }

  if (day.type === 'conditioning') {
    if (settings.easy === true) return 'Облегчённые интервалы: двигайся в разговорном темпе и заканчивай с запасом сил.';
    if (day.week === 7) return 'На этой неделе интервалы короче. Двигайся спокойно, без гонки и максимальных усилий.';
    if (day.week <= 2) return 'Подбери темп, при котором можешь говорить фразами. Дыши свободно и двигайся уверенно.';
    if (day.week <= 4) return 'Интервалы немного длиннее. Сохраняй разговорный темп и уверенные движения.';
    return 'Удерживай ровный темп в более длинных интервалах. Если дыхание сбивается, замедлись или добавь отдых.';
  }

  if (day.type === 'mobility') {
    if (settings.easy === true || day.week === 7) return 'Один лёгкий круг: небольшая комфортная амплитуда и большой запас сил.';
    return day.week <= 2
      ? 'Освой спокойные движения в комфортной амплитуде. Не тяни через боль и не накапливай усталость.'
      : 'Чуть больше плавных повторений. Сохраняй комфортную амплитуду и не меньше пяти повторов в запасе.';
  }

  if (day.type === 'cardio') return settings.easy === true
    ? 'Выбирай спокойный темп и сокращай прогулку по самочувствию. Важно закончить с запасом сил.'
    : day.week <= 2
      ? 'Подбери удобный маршрут и темп, в котором можешь говорить фразами.'
      : 'Сохраняй привычку двигаться в разговорном темпе. При необходимости замедлись или отдохни.';

  return 'Сегодня двигайся легко и без выраженного утомления. Ориентир — готовность к следующему силовому дню.';
}

export function getDayPurpose(index, settings = {}) {
  const day = getDay(index, settings);
  const purpose = { ...PURPOSES[day.code] };
  if (day.type === 'recovery' && index % 7 === 2) {
    purpose.focus = 'Комфортную подвижность и привычку к лёгкой активности.';
    purpose.why = 'Мягкая мобильность и спокойная прогулка сохраняют ритм между силовыми занятиями.';
  }
  return { ...purpose, weekFocus: weeklyFocus(day, settings) };
}
